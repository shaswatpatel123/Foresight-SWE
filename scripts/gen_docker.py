GO_BASE_DOCKERFILE = """\
# Auto-generated by scripts/gen_docker.py -- TIER 1 (base), Go {gover}.
# Shared by every repo on this Go version. Holds only what is repo-independent: the
# toolchain, git, python3 (for the JUnit converter), and the run/grade scripts.
#
# WHY THE VERSION IS PINNED AND NOT LEFT TO `toolchain:`. Go 1.21+ will silently
# DOWNLOAD a newer toolchain when a go.mod asks for one, which would make the image tag
# a lie -- the planner pinned this image to serve one era, and a self-upgrading
# toolchain would run a different compiler than the plan says. GOTOOLCHAIN=local
# forbids that: a module needing something newer fails loudly and is recorded, rather
# than quietly building on an unplanned compiler.
#
# THE DEBIAN SUITE IS PER GO VERSION, not fixed: an image is built on the Debian of its
# day, so golang:1.16/1.17/1.18 exist ONLY for bullseye and bookworm starts at 1.19.
# Hardcoding bookworm made every pre-1.19 base fail with "not found" -- the same shape
# as the node base's buster note.
FROM golang:{gover}-{suite}

ENV DEBIAN_FRONTEND=noninteractive \\
    REPO_DIR=/testbed \\
    GOVER={gover} \\
    GOTOOLCHAIN=local \\
    GOPATH=/go \\
    GOMODCACHE=/go/pkg/mod \\
    GOCACHE=/root/.cache/go-build \\
    CGO_ENABLED=1

# NO apt STEP, deliberately. The golang image already carries git, python3, ca-certs
# and a C toolchain (CGO_ENABLED=1 needs the last -- gitea has cgo
# packages). Installing them anyway is not merely redundant, it is a live failure: an
# old image pins an old Debian, and that suite's security repo eventually EXPIRES --
# measured on golang:1.17-bullseye, whose bullseye-security Release went invalid and
# made `apt-get update` exit 100, breaking every pre-1.19 base build.

# PATH FOR LOGIN SHELLS. The golang image puts the toolchain in /usr/local/go/bin via
# ENV, but the installer agent execs `docker exec ... bash -lc`, and Debian's
# /etc/profile OVERWRITES PATH for a login shell -- so `go` is not found and the agent
# spends a step symlinking it, baking that workaround into the recipe. Measured on
# base-go1.25: non-login PATH has /usr/local/go/bin, `bash -lc` does not.
# Go is the first image where the toolchain lives outside /usr/local/bin, which is why
# python and node never tripped over this.
RUN printf 'export PATH=/go/bin:/usr/local/go/bin:$PATH\\n' > /etc/profile.d/go.sh \\
    && chmod 0644 /etc/profile.d/go.sh

# go_run_tests.sh is shared by run_state_go.sh and run_era.sh so the invocation and the
# JUnit normalisation cannot drift. build_env_go.sh must be on PATH because tier 3
# invokes it by bare name.
COPY run_state_go.sh go_run_tests.sh go_to_junit.py run_era.sh build_env_go.sh /usr/local/bin/
RUN chmod +x /usr/local/bin/run_state_go.sh /usr/local/bin/go_run_tests.sh \\
             /usr/local/bin/run_era.sh /usr/local/bin/build_env_go.sh

WORKDIR /testbed
CMD ["/bin/bash"]
"""

