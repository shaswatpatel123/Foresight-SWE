def _git(repo_path: Path, *a: str) -> str:
    return subprocess.run(["git", "-C", str(repo_path), *a],
                          capture_output=True, text=True, errors="replace").stdout


def rev_parse(repo: str, ref: str) -> str:
    """Ref -> full SHA."""
    if not ref:
        return ""
    s = _git(config.get_target(repo).path, "rev-parse", ref).strip()
    return s if len(s) == 40 else ref


def test_files(repo: str, base: str, head: str) -> list[str]:
    """Changed test files still at head."""
    t = config.get_target(repo)
    return changed_test_files(t.path, base, head, t.language)


def apt_extra_block(repo: str) -> str:
    extra = REPO_APT_EXTRA.get(repo, "")
    if TARGETS[repo].build_deps and "ccache" not in extra:
        extra = f"{extra} ccache".strip()
    if not extra:
        return ""
    return ("\nRUN apt-get update -qq && apt-get install -y --no-install-recommends \\\n"
            f"        {extra} \\\n    && rm -rf /var/lib/apt/lists/*\n")


def env_dockerfile(repo: str, pyver: str) -> str:
    """Env Dockerfile: clone only."""
    t = TARGETS[repo]
    if getattr(t, "runner", "pytest") == "go":
        return GO_ENV_DOCKERFILE.format(
            slug=t.slug, registry=REGISTRY, gover=pyver,
            clone_url=f"https://github.com/{t.slug}.git",
            clone_flags="--recurse-submodules " if getattr(t, "recurse_submodules", False) else "",
            apt_extra=apt_extra_block(repo))
    if getattr(t, "runner", "pytest") == "node":
        return NODE_ENV_DOCKERFILE.format(
            slug=t.slug, registry=REGISTRY, nodever=pyver,
            clone_url=f"https://github.com/{t.slug}.git",
            clone_flags="--recurse-submodules " if getattr(t, "recurse_submodules", False) else "",
            apt_extra=apt_extra_block(repo))
    if getattr(t, "runner", "pytest") == "django":
        return ENV_DOCKERFILE_DJANGO.format(
            slug=t.slug, registry=REGISTRY, pyver=pyver,
            clone_url=f"https://github.com/{t.slug}.git",
            django_settings=getattr(t, "django_settings", "test_sqlite"))
    ccache_env = (" \\\n    CC=\"ccache cc\" CXX=\"ccache c++\" CCACHE_DIR=/opt/ccache"
                  if t.build_deps else "")
    return ENV_DOCKERFILE.format(
        slug=t.slug, registry=REGISTRY, pyver=pyver,
        clone_url=f"https://github.com/{t.slug}.git",
        clone_flags="--recurse-submodules " if getattr(t, "recurse_submodules", False) else "",
        addopts_clear="1" if getattr(t, "clear_addopts", False) else "0",
        ccache_env=ccache_env, apt_extra=apt_extra_block(repo))


def emit(plan_path: Path, only: set[str], with_files: bool) -> None:
    plan = json.loads(plan_path.read_text())
    # SHAs from the master, then the pool
    pool: dict[str, dict] = {}
    _master = ROOT / "data" / "chains_master.jsonl"
    if _master.exists():
        for line in _master.read_text(errors="replace").splitlines():
            if not line.strip():
                continue
            r = json.loads(line)
            if not r.get("instance_id"):
                continue
            # flatten `filters` fields
            f = r.get("filters") or {}
            for k in ("recency_tier", "pr1_has_test_changes", "pr2_has_test_changes",
                      "pr1_n_test_files", "pr2_n_test_files",
                      "pr1_n_src_files", "pr2_n_src_files"):
                if r.get(k) is None and f.get(k) is not None:
                    r[k] = f[k]
            pool[r["instance_id"]] = r
    for line in (CHAINS / "candidate_pool.jsonl").read_text().splitlines():
        if line.strip():
            r = json.loads(line)
            pool.setdefault(r["instance_id"], r)

    # plan toolchain; default python
    toolchain = plan.get("images", [{}])[0].get("toolchain", "python")
    infix = "py" if toolchain == "python" else toolchain

    def _ver(i: dict) -> str:
        return i.get("version") or i["python"]

    images = [i for i in plan["images"]
              if not only or f"{i['repo']}-{infix}{_ver(i)}" in only]
    (DOCKER / "base").mkdir(parents=True, exist_ok=True)

    # ---- tier 1: one per version
    vers = sorted({_ver(i) for i in images})
    for v in vers:
        if toolchain == "python":
            (DOCKER / "base" / f"py{v}.Dockerfile").write_text(
                BASE_DOCKERFILE.format(pyver=v, uv=UV_VERSION))
        elif toolchain == "go":
            minor = int(str(v).split(".")[1])
            suite = "bullseye" if minor < 19 else "bookworm"
            (DOCKER / "base" / f"go{v}.Dockerfile").write_text(
                GO_BASE_DOCKERFILE.format(gover=v, suite=suite))
        else:
            (DOCKER / "base" / f"node{v}.Dockerfile").write_text(
                NODE_BASE_DOCKERFILE.format(nodever=v,
                                            jest_junit=JEST_JUNIT_VERSION,
                                            mocha_junit=MOCHA_JUNIT_VERSION))

    if toolchain != "python":
        print(f"toolchain={toolchain}: wrote {len(vers)} base Dockerfile(s)")

    # ---- tier 2 + per-era routing; cross is PR1
    routes: dict[str, dict] = {}
    env_names = []
    for img in images:
        repo, pyver = img["repo"], _ver(img)
        name = f"{repo}-{infix}{pyver}"
        d = DOCKER / "env" / name
        d.mkdir(parents=True, exist_ok=True)
        (d / "Dockerfile").write_text(env_dockerfile(repo, pyver))
        env_names.append(name)
        for iid in img["pr1_instances"]:
            r = routes.setdefault(iid, {"repo": repo})
            r.update({"pr1_base": name, "pr1_head": name, "cross": name})
        for iid in img["pr2_instances"]:
            r = routes.setdefault(iid, {"repo": repo})
            r.update({"pr2_base": name, "pr2_head": name})

    # recipe dir must exist for COPY
    for repo in sorted({i["repo"] for i in images}):
        rd = DOCKER / "install" / repo
        rd.mkdir(parents=True, exist_ok=True)
        (rd / ".keep").write_text("")

    # ---- tier 3 (two per chain) + manifests
    val_manifest, eval_manifest = [], []
    n_inst = 0
    for iid, r in sorted(routes.items()):
        p = pool.get(iid, {})
        repo = r["repo"]
        runner = getattr(TARGETS.get(repo), "runner", "pytest")
        shas = {k: rev_parse(repo, p.get(k, ""))
                for k in ("pr1_base_sha", "pr1_head_sha", "pr2_base_sha", "pr2_head_sha")}
        val_manifest.append({
            "instance_id": iid, "repo": repo,
            # eras in different images
            "split_image": r.get("pr1_base") != r.get("pr2_base"),
            "runner": runner, "recency_tier": p.get("recency_tier"),
            "images": {s: r.get(s) for s in
                       ("pr1_base", "pr1_head", "pr2_base", "pr2_head", "cross")},
            **shas,
        })

        # one Dockerfile per era; -pr1 ships
        for era, env_key, build_sha, build_name in (
                ("pr1", "pr1_base", shas["pr1_base_sha"], "pr1_base_sha"),
                ("pr2", "pr2_head", shas["pr2_head_sha"], "pr2_head_sha")):
            env_image = r.get(env_key)
            if not env_image or not build_sha:
                continue          # not selected
            d = DOCKER / "inst" / f"{iid}-{era}"
            d.mkdir(parents=True, exist_ok=True)
            tmpl = (NODE_INST_DOCKERFILE if runner == "node" else INST_DOCKERFILE)
            (d / "Dockerfile").write_text(tmpl.format(
                iid=iid, era=era, repo=repo, registry=REGISTRY, env_image=env_image,
                build_sha=build_sha, build_sha_name=build_name,
                pr1_base=shas["pr1_base_sha"], pr1_head=shas["pr1_head_sha"],
                pr2_base=shas["pr2_base_sha"], pr2_head=shas["pr2_head_sha"]))
            n_inst += 1

        # eval manifest: -pr1 only
        env_image = r.get("pr1_base")
        if not env_image:
            continue
        row = {
            "instance_id": iid, "repo": repo, "runner": runner,
            "image": f"inst-{iid}-pr1", "env_image": f"env-{env_image}",
            # version from the env tag
            "python": (env_image.rsplit("-node", 1)[-1] if "-node" in env_image
                       else env_image.rsplit("py", 1)[-1]),
            "start_commit": shas["pr1_base_sha"],
            "pr1_head_sha": shas["pr1_head_sha"],
            "pr2_head_sha": shas["pr2_head_sha"],
        }
        if with_files:
            row["pr1_test_files"] = test_files(repo, shas["pr1_base_sha"],
                                               shas["pr1_head_sha"])
            row["anticipation_test_files"] = test_files(repo, shas["pr2_base_sha"],
                                                        shas["pr2_head_sha"])
        eval_manifest.append(row)

    # --only runs keep the manifests
    if only:
        print(f"--only {sorted(only)}: Dockerfiles rewritten, manifests LEFT ALONE "
              f"(they describe all images; re-run without --only to refresh them)")
    else:
        # one manifest per language
        suffix = "" if toolchain == "python" else f"_{plan.get('language', toolchain)}"
        (DOCKER / f"validate_instances{suffix}.json").write_text(
            json.dumps(val_manifest, indent=2) + "\n")
        (DOCKER / f"eval_instances{suffix}.json").write_text(
            json.dumps(eval_manifest, indent=2) + "\n")
    (DOCKER / "README.md").write_text(README)

    print(f"tier 1 base    : {len(vers)} -> docker/base/{infix}<ver>.Dockerfile {vers}")
    print(f"tier 2 env     : {len(env_names)} -> docker/env/<repo>-{infix}<ver>/  (thin)")
    print(f"tier 3 instance: {n_inst} -> docker/inst/<instance_id>-{{pr1,pr2}}/")
    print(f"manifests      : validate_instances{suffix if not only else ''}.json ({len(val_manifest)}, "
          f"{sum(1 for m in val_manifest if m['split_image'])} with their two eras "
          f"in different images), eval_instances.json ({len(eval_manifest)})")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--plan", default=str(CHAINS / "docker_plan.json"))
    ap.add_argument("--only", default="",
                    help="comma list of <repo>-py<ver> to emit (default: all)")
    ap.add_argument("--no-test-files", action="store_true",
                    help="skip the per-instance git diffs that populate the eval "
                         "manifest's test-file lists (faster for a pilot)")
    args = ap.parse_args()
    emit(Path(args.plan),
         {s.strip() for s in args.only.split(",") if s.strip()},
         not args.no_test_files)


if __name__ == "__main__":
    main()
